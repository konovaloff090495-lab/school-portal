export function getOnlineBrand(slug: string): OnlineBrand | undefined {
  return onlineBrands.find(b => b.slug === slug)
}

/** Сортировка для таблицы сравнения: сначала школы с собственной аккредитацией, внутри — по цене */
export function onlineBrandsForTable(all = false): OnlineBrand[] {
  return [...onlineBrands].filter(b => all || (b.tier ?? 1) === 1).sort((a, b) => {
    if (a.attestation !== b.attestation) return a.attestation === 'own' ? -1 : 1
    const pa = a.priceFrom || 10 ** 9
    const pb = b.priceFrom || 10 ** 9
    return pa - pb
  })
}
