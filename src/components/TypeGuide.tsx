export default function TypeGuide({ type }: { type: SchoolType }) {
  const guide = GUIDES[type]
  if (!guide) return null

  return (
    <div style={{ maxWidth: 860, margin: '0 auto', padding: '0 0 40px', fontFamily: 'var(--font-manrope, system-ui)' }}>
      <p style={{ fontSize: 16, lineHeight: 1.7, color: '#4A453E', margin: '0 0 28px' }}>{guide.intro}</p>

      {guide.sections.map(s => (
        <section key={s.h} style={{ margin: '0 0 28px' }}>
          <h2 style={{ fontSize: 20, fontWeight: 700, color: '#1A1814', margin: '0 0 12px', lineHeight: 1.3 }}>{s.h}</h2>
          {s.p.map((text, i) => (
            <p key={i} style={{ fontSize: 15, lineHeight: 1.75, color: '#4A453E', margin: '0 0 12px' }}>{text}</p>
          ))}
        </section>
      ))}

      <section>
        <h2 style={{ fontSize: 20, fontWeight: 700, color: '#1A1814', margin: '0 0 16px', lineHeight: 1.3 }}>
          Частые вопросы
        </h2>
        {guide.faqs.map(f => (
          <details
            key={f.question}
            style={{ borderBottom: '1px solid #E8E0D6', padding: '14px 0' }}
          >
            <summary style={{ fontSize: 15, fontWeight: 700, color: '#1A1814', cursor: 'pointer', listStyle: 'none' }}>
              {f.question}
            </summary>
            <p style={{ fontSize: 15, lineHeight: 1.7, color: '#4A453E', margin: '10px 0 0' }}>{f.answer}</p>
          </details>
        ))}
      </section>

      <FaqJsonLd faqs={guide.faqs} />
    </div>
  )
}
