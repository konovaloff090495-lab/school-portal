export type SuProductKey = keyof typeof SU_PRODUCTS

/**
 * Партнёрская ссылка на посадочную school-university.com.
 * @param productKey ключ из SU_PRODUCTS
 * @param place      где стоит ссылка: banner | cta | text | <произвольная метка>
 * @param postSlug   slug статьи-донора (уходит в utm_content — видно, какая статья даёт заявки)
 * @param pathOverride глубокая посадочная вместо хаба, например /kursy-ege/matematika/
 */
export function suUrl(
  productKey: string,
  place: string,
  postSlug?: string,
  pathOverride?: string,
): string {
  const product = SU_PRODUCTS[productKey]
  const path = pathOverride || product?.path || '/'
  const params = new URLSearchParams({
    utm_source: SU_UTM_SOURCE,
    utm_medium: SU_UTM_MEDIUM,
    utm_campaign: SU_UTM_CAMPAIGN,
    utm_term: `${productKey}-${place}`,
  })
  if (postSlug) params.set('utm_content', postSlug)
  return `${SU_BASE}${path}?${params.toString()}`
}

export function getSuProduct(key?: string): SuProduct | undefined {
  return key ? SU_PRODUCTS[key] : undefined
}
