/**
 * rlic-address.mjs — приведение адреса из реестра Рособрнадзора к виду «улица, дом».
 *
 * Общий для rlic-schools.mjs и rlic-chess.mjs. Вынесено, потому что реестр отдаёт
 * адрес одной строкой с индексом, субъектом, районом и офисным хвостом, а на
 * карточке нужен только адрес в пределах города.
 *
 * NB: \b в JS не работает с кириллицей (граница слова — только ASCII), поэтому
 * границы слов задаются lookaround'ами по кириллице.
 */
// Регистр слова: КАПС → Титул, иначе оставляем (чтобы не ломать «МБОУ», «им.»)
const SMALL = new Set(['на','в','во','по','и','с','к','о','от','до','для','при','из','за','над','под','у'])
function titleWord(w, i) {
  if (w.length <= 1) return w
  const low = w.toLowerCase()
  if (i > 0 && SMALL.has(low)) return low
  if (w === w.toUpperCase() && /[А-ЯЁA-Z]/.test(w)) return w.charAt(0) + low.slice(1)
  return w
}
export function titleCase(s) {
  let idx=0; return s.split(/(\s+|-)/).map(t=>/^[\s-]+$/.test(t)?t:titleWord(t,idx++)).join('')
}

export function cleanAddress(raw, cityName) {
  if (!raw) return `г. ${cityName}`
  // \b в JS не работает с кириллицей (граница слова — только ASCII), поэтому
  // используем lookaround по кириллице. NB — «не буква кириллицы» слева/справа.
  const NB = '(?<![А-ЯЁа-яё])', NA = '(?![А-ЯЁа-яё])'
  const w = (body, flags='ig') => new RegExp(NB + body + NA, flags)
  const C = '[А-ЯЁа-яё]'
  let a = ' ' + raw + ' '
  a = a.replace(/(^|,)\s*\d{5,6}\s*,?/g, ',')                        // индекс в любом месте
    .replace(/Российская Федерация\s*,?/ig, ' ')
    .replace(w('г(ород)?\\.?\\s*(москв'+C+'*|санкт-?петербург'+C+'*|севастопол'+C+'*)\\s*,?'), ' ')
    .replace(/ВН\.?\s*ТЕР\.?\s*Г\.?\s*/ig, ' ')
    .replace(/муниципальн[а-яё]*\s+округ[а-яё]*\s*(№\s*\d+|[А-ЯЁа-яё-]+)?\s*,?/ig, ' ')
    .replace(w('поселени'+C+'*\\s+'+C+'[А-ЯЁа-яё-]*\\s*,?'), ' ')
    .replace(w('(населенный пункт\\s+)?(деревня|пос[её]лок|село|рабочий пос[её]лок)\\s+'+C+'[А-ЯЁа-яё-]*\\s*,?'), ' ')
    .replace(/\bж\/?к\s+[А-ЯЁа-яё-]+\s*,?/ig, ' ')
    .replace(w('(помещ'+C+'*|литер[аы]?|каб'+C+'*|комн'+C+'*)\\.?[^,]*'), ' ')      // офисный хвост
    .replace(/,?\s*оф(ис)?\.?\s*[^,]*/ig, ' ').replace(/,?\s*эт(аж)?\.?\s*\d[^,]*/ig, ' ').replace(/,?\s*кв\.?\s*\d[^,]*/ig, ' ')
    .replace(/\s+/g, ' ').replace(/^[,\s]+|[,\s]+$/g, '')
  // сокращения к единому виду (тоже через lookaround)
  const R = [['УЛИЦА','ул.'],['ПЕРЕУЛОК','пер.'],['ПРОЕЗД','проезд'],['УЛ','ул.'],['ПЕР','пер.'],['ПРОСПЕКТ','просп.'],['ПР-?КТ','просп.'],['ШОССЕ','шоссе'],
    ['НАБ','наб.'],['БУЛЬВАР','бул.'],['Б-?Р','бул.'],['ТУП','тупик'],['ПЛ','пл.'],
    ['ДОМ','д.'],['Д','д.'],['СТРОЕНИЕ','стр.'],['СТР','стр.'],['КОРПУС','корп.'],['КОРП?','корп.']]
  for (const [from,to] of R) a = a.replace(w(from+'\\.?'), to)
  a = a.replace(/\s+/g,' ').replace(/\s*,\s*/g,', ').replace(/^[,\s]+|[,\s]+$/g,'')
  // капсовые названия улиц → Титул
  a = a.split(', ').map(part => /^(ул\.|пер\.|просп\.|шоссе|наб\.|бул\.|пл\.|тупик)/i.test(part) ? titleCase(part) : part).join(', ')
  a = a.charAt(0).toUpperCase() + a.slice(1)
  return a && a.length > 3 ? a : `г. ${cityName}`
}

/**
 * Убирает субъект РФ, район и название города — то, что в карточке уже есть
 * в отдельных полях. Нужен для общероссийских выборок (rlic-chess.mjs);
 * для Москвы/СПб/Севастополя эту работу делает сам cleanAddress.
 *
 * Вызывать ДО cleanAddress: тот доводит остаток до вида «ул. Имя, д. N».
 */
export function stripRegionAndCity(raw, cityName) {
  if (!raw) return raw
  const NB = '(?<![А-ЯЁа-яё])', NA = '(?![А-ЯЁа-яё])'
  const w = (body, flags = 'ig') => new RegExp(NB + body + NA, flags)
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  let a = raw
    // «Российская Федерация (Россия)», «Россия», «РФ» в начале
    .replace(/Российская\s+Федерация(\s*\(Россия\))?\s*,?/ig, ' ')
    .replace(w('росси[яи]'), ' ').replace(/\bРФ\b\s*,?/g, ' ')
    // субъект: «Орловская область», «Краснодарский край», «Республика Калмыкия»,
    // «Ямало-Ненецкий автономный округ - Югра»
    .replace(/[^,]*(область|края|край|автономный округ[^,]*|автономная область)[^,]*,?/ig, ' ')
    .replace(/[^,]*республик[аи][^,]*,?/ig, ' ')
    // район / городской округ / территориальный округ
    .replace(/[^,]*\bрайон[а-яё]*\b[^,]*,?/ig, ' ')
    .replace(w('городско[йг][^,]*округ[^,]*') , ' ')
    .replace(/[^,]*территориальный округ[^,]*,?/ig, ' ')
    // сам город
    // ё/е: в реестре «Орел», у нас «Орёл» — сверяем без учёта различия
    .replace(new RegExp('(?:^|,)\\s*(?:г(?:ород)?\\.?\\s*)?' + esc(cityName).replace(/[её]/gi, '[ЕЁеё]') + '\\s*(?=,|$)', 'ig'), ',')
    // офисный хвост из косых: «Э/ПОМ/К/ОФ 3/I/8/38А»
    .replace(/,?\s*[А-ЯЁ]{1,4}\/[^,]*/g, ' ')
    .replace(/\s+/g, ' ').replace(/\s*,\s*/g, ', ').replace(/^[,\s]+|[,\s]+$/g, '')
  return a
}
