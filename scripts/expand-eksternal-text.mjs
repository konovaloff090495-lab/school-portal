const { schools, regionLabelsIn } = await jiti.import(SCHOOLS_TS)

// ── статистика по городу считается из каталога, а не пишется руками ──────────
function cityFacts(s) {
  const same = schools.filter(x => x.region === s.region && x.type === s.type)
  const free = same.filter(x => !x.priceFrom).length
  const paid = same.filter(x => x.priceFrom > 0)
  const minPrice = paid.length ? Math.min(...paid.map(x => x.priceFrom)) : null
  const cityIn = regionLabelsIn[s.region] || `в ${s.city}`
  const label = s.type === 'vechernie' ? ['вечерняя школа', 'вечерние школы', 'вечерних школ'] : ['школа-экстернат', 'школы-экстерната', 'школ-экстернатов']
  const word = plural(same.length, label[0], label[1], label[2])

  const parts = []
  if (same.length >= 3) parts.push(`Всего ${cityIn} в нашем каталоге ${same.length} ${word}.`)
  if (same.length >= 3 && free >= 1 && minPrice) {
    parts.push(`${free} ${plural(free, 'из них ведёт', 'из них ведут', 'из них ведут')} приём бесплатно, платные программы начинаются от ${minPrice.toLocaleString('ru-RU')} ₽ в месяц.`)
  } else if (same.length >= 3 && free >= 1) {
    parts.push(`${free === same.length ? 'Все они' : `${free} из них`} принимают бесплатно — это государственные и муниципальные школы.`)
  }
  return parts.join(' ')
}

// гос/муниципальная школа — по названию: только у неё аттестация экстерном
// заведомо бесплатна. Частному центру приписывать «бесплатно» нельзя.
const STATE_NAME = /ГБОУ|ГАОУ|МБОУ|МАОУ|МКОУ|\bМОУ\b|ГКОУ|государственн|муниципальн|Открытая \(сменная\)|Вечерняя \(сменная\)/i

function moneyLine(s) {
  if (s.priceFrom > 0) {
    return `Обучение платное — от ${s.priceFrom.toLocaleString('ru-RU')} ₽ в месяц. Отдельно стоит уточнить, входит ли в стоимость промежуточная аттестация и подготовка к экзаменам.`
  }
  if (s.type === 'vechernie') return 'Обучение бесплатное: школа финансируется из бюджета.'
  return STATE_NAME.test(s.name)
    ? 'Прохождение промежуточной и итоговой аттестации экстерном здесь бесплатно — школа государственная, платить нужно только за добровольное сопровождение.'
    : 'Стоимость сопровождения уточняйте в школе — она зависит от набора предметов и формата занятий. Само прохождение аттестации экстерном бесплатно в любой государственной школе с аккредитацией.'
}

// ── сборка ───────────────────────────────────────────────────────────────────
const pick = (arr, h, i) => arr[(h + i * 7) % arr.length]
const norm = t => t.toLowerCase().replace(/[^а-яё0-9]+/g, ' ')

function expand(s) {
  const cur = (s.fullDescription || '').trim()
  if (cur.length >= MIN_KEEP) return null
  const h = hash(s.slug)
  const isVech = s.type === 'vechernie'
  const pool = [
    pick(isVech ? VECHERNIE_LAW : LAW, h, 0),
    moneyLine(s),
    cityFacts(s),
    pick(isVech ? VECHERNIE_ADMISSION : ADMISSION, h, 1),
    pick(isVech ? VECHERNIE_EXAMS : EXAMS, h, 2),
    pick(isVech ? VECHERNIE_CLOSING : CLOSING, h, 3),
  ].filter(Boolean)

  const curNorm = norm(cur)
  let out = cur
  for (const block of pool) {
    if (out.length >= TARGET) break
    // не дублируем то, что в тексте уже сказано (у части карточек текст ручной)
    const firstWords = norm(block).split(' ').slice(0, 6).join(' ')
    if (curNorm.includes(firstWords)) continue
    out = out ? `${out} ${block}` : block
  }
  return out === cur ? null : out
}

// --slugs=<json> — ограничиться конкретным списком (напр. только что добавленными
// карточками, чтобы не переписывать давно живущие)
const ONLY_SLUGS = args.slugs ? new Set(JSON.parse(readFileSync(String(args.slugs), 'utf8'))) : null
const targets = schools.filter(s => TYPES.includes(s.type) && (!ONLY_SLUGS || ONLY_SLUGS.has(s.slug)))
const updates = new Map()
for (const s of targets) {
  const next = expand(s)
  if (next) updates.set(s.slug, next)
}
const lens = [...updates.values()].map(t => t.length).sort((a, b) => a - b)
console.error(`Карточек типов ${TYPES.join('/')}: ${targets.length}, расширяем: ${updates.size}`)
if (lens.length) console.error(`Длина после: мин ${lens[0]}, медиана ${lens[Math.floor(lens.length / 2)]}, макс ${lens[lens.length - 1]}`)
const sample = targets.find(s => updates.has(s.slug))
if (sample) console.error(`\nПример (${sample.name}, ${sample.city}):\n${updates.get(sample.slug)}\n`)

if (DRY) { console.error('🔍 DRY — файл не менялся'); process.exit(0) }

// ── запись: подменяем только строку fullDescription внутри нужного блока ─────
let src = readFileSync(SCHOOLS_TS, 'utf8')
const esc = v => String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
const marker = 'export const schools = (['
const endMarker = '] as any[] as School[])'
const head = src.slice(0, src.indexOf(marker) + marker.length)
const tail = src.slice(src.lastIndexOf(endMarker))
const body = src.slice(head.length, src.lastIndexOf(endMarker))

let written = 0
const blocks = body.split(/\n(?=\s*\{\n)/).map(b => {
  const m = b.match(/slug:\s*'([^']+)'/)
  if (!m || !updates.has(m[1])) return b
  const next = updates.get(m[1])
  const re = /(\n\s*fullDescription:\s*)'(?:[^'\\]|\\.)*'/
  if (!re.test(b)) return b
  written++
  return b.replace(re, `$1'${esc(next)}'`)
})

writeFileSync(SCHOOLS_TS, head + blocks.join('\n') + tail, 'utf8')
console.error(`💾 schools.ts обновлён, переписано карточек: ${written}`)
