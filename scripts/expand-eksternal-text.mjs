#!/usr/bin/env node
/**
 * expand-eksternal-text.mjs — дописывает fullDescription карточкам экстернатов
 * и вечерних школ до 1200–1500 знаков.
 *
 * Зачем: у карточек этих типов медиана уникального текста была ~430 знаков,
 * при этом 286 из них уже показываются в Google на 8–9 месте — им не хватает
 * глубины, а не позиций.
 *
 * Что дописываем: только то, что либо следует из закона (273-ФЗ: формы получения
 * образования вне организации, права экстерна, порядок аттестации), либо
 * посчитано по нашему же каталогу (сколько таких школ в городе, есть ли бесплатные,
 * от какой цены начинается платный формат). Ничего про конкретную школу,
 * чего мы не знаем, не выдумываем.
 *
 * Существующий текст сохраняется как начало — дописываем в конец.
 * Карточки, где уже ≥ MIN_KEEP знаков, не трогаем.
 *
 * Запуск: node scripts/expand-eksternal-text.mjs [--dry] [--types=eksternal,vechernie]
 */

import { readFileSync, writeFileSync } from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { createJiti } from '../node_modules/jiti/lib/jiti.mjs'

const __dirname  = path.dirname(fileURLToPath(import.meta.url))
